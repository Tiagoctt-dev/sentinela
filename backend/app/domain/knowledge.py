def owasp_ref(owasp_id: str) -> dict | None:
    key = (owasp_id or "").split(":")[0]
    slug = OWASP_SLUG.get(key)
    if not slug:
        return None
    return {"label": f"OWASP API Security Top 10 2023 — {owasp_id}", "url": f"https://owasp.org/API-Security/editions/2023/en/{slug}/"}


def cwe_ref(n: int) -> dict:
    return {"label": f"CWE-{n}", "url": f"https://cwe.mitre.org/data/definitions/{n}.html"}


