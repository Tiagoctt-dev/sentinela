# critérios de aprovação/falha, pré-requisitos, impacto, cenário e limitações.
# É a única fonte desse texto: os probes só produzem os FATOS (requisição,
# resposta, status); este módulo explica o que eles significam.
#
# `proof` define o quanto uma falha desta verificação PROVA:
#   "confirmed"  — a própria condição da falha foi observada (ex.: token forjado aceito).
#   "indicative" — é um indício que exige validação (ex.: nenhum 429 em 20 requisições).

