def knowledge_for(check_id: str) -> dict | None:
    if check_id in KNOWLEDGE:
        return KNOWLEDGE[check_id]
    if check_id.startswith("D-AUTHZ-"):
        return KNOWLEDGE["D-AUTHZ-0N"]
    if check_id.startswith("D-BFLA-") and check_id != "D-BFLA-A1":
        return KNOWLEDGE["D-BFLA-0N"]
    return None
